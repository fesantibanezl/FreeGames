-- FreeGames - estructura de las seis tablas propias de la aplicacion
-- Motor: Oracle Database 19c o superior
-- Generado a partir de las migraciones 0001 y 0003 de la app tienda.
--
-- Requisito: AUTH_USER debe existir porque Django administra autenticacion.
-- La forma recomendada de crear el esquema completo es: python manage.py migrate
-- Este archivo permite revisar o crear manualmente las tablas de negocio.

SET DEFINE OFF;

CREATE TABLE TIENDA_ROL (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODIGO NVARCHAR2(20) UNIQUE,
    NOMBRE NVARCHAR2(40),
    DESCRIPCION NVARCHAR2(180)
);

CREATE TABLE TIENDA_PERFILUSUARIO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FECHA_NACIMIENTO DATE,
    DIRECCION NVARCHAR2(160),
    CREADO_EN TIMESTAMP NOT NULL,
    ACTUALIZADO_EN TIMESTAMP NOT NULL,
    USUARIO_ID NUMBER(11) NOT NULL UNIQUE,
    ROL_ID NUMBER(19) NOT NULL,
    CONSTRAINT TIENDA_PE_USUARIO_I_12979B97_F
        FOREIGN KEY (USUARIO_ID) REFERENCES AUTH_USER (ID)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT TIENDA_PE_ROL_ID_CABD633E_F
        FOREIGN KEY (ROL_ID) REFERENCES TIENDA_ROL (ID)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX TIENDA_PER_ROL_ID_CABD633E
    ON TIENDA_PERFILUSUARIO (ROL_ID);

CREATE TABLE TIENDA_CATEGORIA (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SLUG NVARCHAR2(30) UNIQUE,
    NOMBRE NVARCHAR2(40) UNIQUE,
    ICONO NVARCHAR2(8),
    CLASE_CSS NVARCHAR2(40),
    RESUMEN NVARCHAR2(100),
    DESCRIPCION_META NVARCHAR2(160),
    IMAGEN NVARCHAR2(160),
    IMAGEN_ALT NVARCHAR2(180),
    ORDEN NUMBER(11) NOT NULL CHECK (ORDEN >= 0)
);

CREATE TABLE TIENDA_JUEGO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SLUG NVARCHAR2(80) UNIQUE,
    NOMBRE NVARCHAR2(60) UNIQUE,
    DESCRIPCION NVARCHAR2(220),
    PRECIO NUMBER(11) NOT NULL CHECK (PRECIO >= 0),
    STOCK NUMBER(11) NOT NULL CHECK (STOCK >= 0),
    ACTIVO NUMBER(1) NOT NULL CHECK (ACTIVO IN (0, 1)),
    IMAGEN NVARCHAR2(160),
    IMAGEN_ALT NVARCHAR2(180),
    CREADO_EN TIMESTAMP NOT NULL,
    ACTUALIZADO_EN TIMESTAMP NOT NULL,
    CATEGORIA_ID NUMBER(19) NOT NULL,
    CONSTRAINT TIENDA_JU_CATEGORIA_3995C026_F
        FOREIGN KEY (CATEGORIA_ID) REFERENCES TIENDA_CATEGORIA (ID)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX TIENDA_JUE_CATEGORIA__3995C026
    ON TIENDA_JUEGO (CATEGORIA_ID);

CREATE TABLE TIENDA_PEDIDO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODIGO NVARCHAR2(24) UNIQUE,
    ESTADO NVARCHAR2(20),
    TOTAL NUMBER(11) NOT NULL CHECK (TOTAL >= 0),
    CREADO_EN TIMESTAMP NOT NULL,
    USUARIO_ID NUMBER(11) NOT NULL,
    CONSTRAINT TIENDA_PE_USUARIO_I_A3683866_F
        FOREIGN KEY (USUARIO_ID) REFERENCES AUTH_USER (ID)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX TIENDA_PED_USUARIO_ID_A3683866
    ON TIENDA_PEDIDO (USUARIO_ID);

CREATE TABLE TIENDA_DETALLEPEDIDO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE_JUEGO NVARCHAR2(60),
    PRECIO_UNITARIO NUMBER(11) NOT NULL CHECK (PRECIO_UNITARIO >= 0),
    CANTIDAD NUMBER(11) NOT NULL CHECK (CANTIDAD >= 0),
    JUEGO_ID NUMBER(19) NOT NULL,
    PEDIDO_ID NUMBER(19) NOT NULL,
    CONSTRAINT DETALLE_PEDIDO_JUEGO_UNICO
        UNIQUE (PEDIDO_ID, JUEGO_ID),
    CONSTRAINT TIENDA_DE_JUEGO_ID_5973A4A1_F
        FOREIGN KEY (JUEGO_ID) REFERENCES TIENDA_JUEGO (ID)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT TIENDA_DE_PEDIDO_ID_B3EB1187_F
        FOREIGN KEY (PEDIDO_ID) REFERENCES TIENDA_PEDIDO (ID)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX TIENDA_DET_JUEGO_ID_5973A4A1
    ON TIENDA_DETALLEPEDIDO (JUEGO_ID);

CREATE INDEX TIENDA_DET_PEDIDO_ID_B3EB1187
    ON TIENDA_DETALLEPEDIDO (PEDIDO_ID);

COMMIT;

-- Comprobacion rapida de las tablas creadas.
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'TIENDA_ROL',
    'TIENDA_PERFILUSUARIO',
    'TIENDA_CATEGORIA',
    'TIENDA_JUEGO',
    'TIENDA_PEDIDO',
    'TIENDA_DETALLEPEDIDO'
)
ORDER BY TABLE_NAME;
